def commodities_table(conn: Conn) -> Table:
    return Table(
        slug="tab_commodities",
        caption="Commodities tracked, with canonical units and plausibility bands.",
        rows=fetch_all(
            conn,
            """
            select c.slug, c.display_name, c.canonical_unit,
                   c.price_min_plausible::bigint as plausible_min,
                   c.price_max_plausible::bigint as plausible_max
              from public.commodities c
             order by c.sort_order
            """,
        ),
        note=(
            "The plausibility band rejects unit and parsing errors before analysis; "
            "a rejected observation is recorded, never silently dropped."
        ),
    )


def sources_table(conn: Conn) -> Table:
    return Table(
        slug="tab_sources",
        caption="Data sources, their cadence and the observations collected from each.",
        rows=fetch_all(
            conn,
            """
            select s.slug, s.cadence, s.is_active,
                   count(o.id) as observations,
                   min(o.obs_date) as first_date,
                   max(o.obs_date) as last_date
              from public.sources s
              left join public.price_observations o on o.source_id = s.id
             group by s.id, s.slug, s.cadence, s.is_active
             order by s.slug
            """,
        ),
        note=(
            "An inactive source is one whose portal is broken upstream; its absence is "
            "recorded in fetch_failures rather than filled in."
        ),
    )


def coverage_table(conn: Conn) -> Table:
    return Table(
        slug="tab_coverage",
        caption="Unified daily series: coverage and imputation per region.",
        rows=fetch_all(
            conn,
            """
            select rg.slug as region,
                   count(*) as series_days,
                   count(*) filter (where u.price_median is not null) as with_price,
                   count(*) filter (where u.is_imputed) as imputed,
                   round(avg(u.n_sources)::numeric, 3) as mean_sources,
                   min(u.obs_date) as first_date,
                   max(u.obs_date) as last_date
              from public.price_daily_unified u
              join public.regions rg on rg.id = u.region_id
             group by rg.slug, rg.level
             order by case rg.level
                        when 'national' then 0 when 'province' then 1 else 2
                      end, rg.slug
            """,
        ),
        note=(
            "Imputed days are interpolated across gaps of at most three days and are "
            "excluded from every model input; the column is reported so the reader can "
            "see how much of the series is not observation."
        ),
    )


def flag_counts_table(conn: Conn, anomaly_run_id: int) -> Table:
    return Table(
        slug="tab_flag_counts",
        caption="Days flagged by each detector, and their overlap.",
        rows=fetch_all(
            conn,
            """
            with f as (
              select method, commodity_id, region_id, obs_date
                from public.anomaly_scores
               where run_id = %s and is_flagged
            )
            select method,
                   count(*) as flagged,
                   count(*) filter (where exists (
                       select 1 from f o
                        where o.method <> f.method
                          and o.commodity_id = f.commodity_id
                          and o.region_id    = f.region_id
                          and o.obs_date     = f.obs_date)) as also_flagged_by_the_other
              from f
             group by method
             order by method
            """,
            (anomaly_run_id,),
        ),
        note=(
            "Low overlap is the premise of the hybrid: two detectors that agreed on "
            "everything would make the fusion step pointless."
        ),
    )


def k_search_table(rows: list[dict[str, Any]]) -> Table:
    # Computed, not written down: the margin moves with the data, and a note that
    # hardcodes it goes stale without anything failing. That is exactly how this
    # table came to carry an editorial constraint two milestones after its removal.
    selected = next((r for r in rows if r["selected"]), None)
    runner_up = max(
        (r for r in rows if not r["selected"]), key=lambda r: r["silhouette"], default=None
    )
    if selected is None or runner_up is None:
        note = "Every k in the search range is fitted, scored and reported."
    else:
        note = (
            f"k={selected['k']} is selected on silhouette alone, ahead of k={runner_up['k']} "
            f"by {selected['silhouette'] - runner_up['silhouette']:.4f}. The three-zone floor "
            f"that once excluded k=2 was removed in M10; every k in the range is fitted, "
            f"scored and reported, and the highest score wins."
        )
    return Table(
        slug="tab_k_search",
        caption="K-Means model selection: silhouette and inertia across the search range.",
        rows=rows,
        note=note,
    )


