"""Tables for the paper: CSV for the data, LaTeX for the manuscript.

Both formats come from one list-of-dicts so they cannot disagree. The CSV is the
artefact a reader can check; the LaTeX is a convenience for typesetting and is
deliberately plain — `booktabs` rules, no colour, no vertical lines, so it works
in a printed monochrome proceedings.

Numbers are written at the precision they were computed at. Rounding for display
happens in the LaTeX only, never in the CSV, so nothing is lost between the
database and the archive.
"""

from __future__ import annotations

import csv
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ..db import Conn, fetch_all

log = logging.getLogger(__name__)

# LaTeX's ten special characters. A commodity name with an ampersand in it
# should not silently produce an unbuildable manuscript.
LATEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


@dataclass
class Table:
    slug: str
    caption: str
    rows: list[dict[str, Any]]
    note: str = ""

    @property
    def columns(self) -> list[str]:
        return list(self.rows[0]) if self.rows else []


def _latex_escape(value: Any) -> str:
    if value is None:
        return "--"
    text = str(value)
    return "".join(LATEX_ESCAPES.get(ch, ch) for ch in text)


def _format_cell(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:.4f}"
    return _latex_escape(value)


def write_csv(table: Table, directory: Path) -> Path:
    path = directory / f"{table.slug}.csv"
    with path.open("w", newline="", encoding="utf-8") as handle:
        if not table.rows:
            handle.write("")
            return path
        writer = csv.DictWriter(handle, fieldnames=table.columns)
        writer.writeheader()
        writer.writerows(table.rows)
    return path


def write_latex(table: Table, directory: Path) -> Path:
    path = directory / f"{table.slug}.tex"
    if not table.rows:
        path.write_text(
            f"% {table.slug}: no rows.\n% {table.note}\n",
            encoding="utf-8",
        )
        return path

    columns = table.columns
    # Numeric columns right-aligned, everything else left. Guessing from the
    # first row is enough here and beats hand-maintaining a spec per table.
    alignment = "".join("r" if isinstance(table.rows[0][c], (int, float)) else "l" for c in columns)

    lines = [
        "% Generated by `siap export`. Do not edit; regenerate.",
        r"\begin{table}[htbp]",
        r"  \centering",
        f"  \\caption{{{_latex_escape(table.caption)}}}",
        f"  \\label{{tab:{table.slug.replace('_', '-')}}}",
        f"  \\begin{{tabular}}{{{alignment}}}",
        r"    \toprule",
        "    " + " & ".join(_latex_escape(c.replace("_", " ")) for c in columns) + r" \\",
        r"    \midrule",
    ]
    for row in table.rows:
        lines.append("    " + " & ".join(_format_cell(row[c]) for c in columns) + r" \\")
    lines += [r"    \bottomrule", r"  \end{tabular}"]
    if table.note:
        lines.append(f"  \\par\\smallskip\\footnotesize {_latex_escape(table.note)}")
    lines += [r"\end{table}", ""]

    path.write_text("\n".join(lines), encoding="utf-8")
    return path


